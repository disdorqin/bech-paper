"""WP-1 P0-A validation — canonical-16 old-vs-new final point comparison.

Old (R1B_STAGE2D): headline mae/smape = day["host_day"] (WRONG口径, it is the
  HOST forecast, not the corrected output). host_mae = panel host raw mae.
New (P0A_RERUN): final_mae / final_smape = x_final = s·sinh(z0+pi_eff) of the
  SELECTED A2 policy. final_host_mae = the host forecast MAE (old 'mae').

Checks:
  1. final_host_mae == old mae (the old column was the host forecast) → confirms
     old-vs-new mapping, not a re-run of the whole chain.
  2. final_mae = x_final TRUE correction (≠ host), A1 vs A2 deltas shown.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

OLD = Path(sys.argv[1]) if len(sys.argv) > 1 else None
NEW = Path(sys.argv[2]) if len(sys.argv) > 2 else None


def _load_csv(p: Path) -> dict[str, dict]:
    with open(p, encoding="utf-8") as f:
        return {r["domain"]: r for r in csv.DictReader(f)}


def main():
    old_dir = OLD or Path(
        r"D:/作业/science/solar_leak_price_model/experiments/08-hch-v2/results/"
        r"R1B_STAGE2D_20260813_165807")
    new_dir = NEW or Path(
        r"D:/作业/science/solar_leak_price_model/experiments/08-hch-v2/results/"
        r"P0A_RERUN_20260814")
    old = _load_csv(old_dir / "action_chain_matrix.csv")
    new = _load_csv(new_dir / "action_chain_matrix.csv")

    print(f"{'domain':20s} {'old_mae':>9s} {'new_host_mae':>12s} "
          f"{'Δhost':>7s} {'final_mae':>9s} {'Δ_final':>8s} "
          f"{'old_smape':>9s} {'final_smape':>11s} {'sel':>5s}")
    n_host_mismatch = 0
    for dom in sorted(new):
        o = old.get(dom)
        n = new[dom]
        if o is None:
            print(f"{dom:20s}  (new-only)")
            continue
        try:
            o_mae = float(o.get("mae")); n_host = float(n.get("final_host_mae"))
            f_mae = float(n.get("final_mae")); o_sm = float(o.get("smape_nofloor"))
            f_sm = float(n.get("final_smape"))
        except (TypeError, ValueError):
            print(f"{dom:20s}  (missing metric)")
            continue
        d_host = n_host - o_mae
        d_final = f_mae - n_host
        if abs(d_host) > 1e-3:
            n_host_mismatch += 1
        print(f"{dom:20s} {o_mae:9.3f} {n_host:12.3f} {d_host:7.3f} "
              f"{f_mae:9.3f} {d_final:8.3f} {o_sm:9.2f} {f_sm:11.2f} "
              f"{n.get('selected',''):>5s}")
    print(f"\nhost mismatch (>1e-3): {n_host_mismatch} / {len(old)} "
          f"(0 = old mae == new final_host_mae, mapping confirmed)")
    print("NOTE: LSTM/PatchTST caches were REGENERATED by the P0-A rerun "
          "(R1B-era caches were legacy 4-segment).")
    print("Mismatch on those hosts = host model refit, NOT a P0-A defect. "
          "Linear/MLP caches unchanged -> exact match.")
    print("d_final = final_mae - final_host_mae  (<0 = x_final improves on host)")


if __name__ == "__main__":
    main()
